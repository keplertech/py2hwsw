# RTL sequential equivalence check (SEC) of one py2hwsw core across one commit.
#
# Generates the core with py2hwsw as of <commit>^ (design 1) and as of <commit>
# (design 2), then runs kepler-formal RTL SEC between the two generated trees.
#
# Usage:
#   keplertech/sec_commit.sh <core> <commit> [engine] [max_k]
#     core    py2hwsw core name, for example iob_axi2iob
#     commit  commit to check; design 1 is its parent
#     engine  pdr (default), k_induction or imc
#     max_k   SEC bound (default 32)
#
# Environment:
#   KEPLER_FORMAL   kepler-formal executable (default: kepler-formal on PATH)
#   PYTHON          Python interpreter with keplertech/requirements.txt installed
#                   (default: python3)
#   RESET_PORT      top-level reset port and active value (default: arst_i=1)
#   RESET_CYCLES    reset bootstrap cycles (default: 4)
#
# Exit code: the kepler-formal SEC exit code
#   0 proved, 1 partially proved, 2 inconclusive, 3 counterexample.

set -euo pipefail

if [ $# -lt 2 ]; then
    sed -n '9,27p' "$0"
    exit 64
fi

CORE=$1
COMMIT=$2
ENGINE=${3:-pdr}
MAX_K=${4:-32}
KEPLER_FORMAL=${KEPLER_FORMAL:-kepler-formal}
PYTHON=${PYTHON:-python3}
RESET_PORT=${RESET_PORT:-arst_i=1}
RESET_CYCLES=${RESET_CYCLES:-4}

REPO=$(git -C "$(dirname "$0")" rev-parse --show-toplevel)
SHORT=$(git -C "$REPO" rev-parse --short "$COMMIT")
WORK=$REPO/keplertech/work/${CORE}_${SHORT}
mkdir -p "$WORK"

# py2hwsw setup formats the generated Verilog with verible-verilog-format and
# fails if it is missing, after all sources are generated. Formatting does not
# change the RTL, so without verible a no-op formatter is put on PATH.
if ! command -v verible-verilog-format >/dev/null 2>&1; then
    SHIM=$REPO/keplertech/work/bin
    mkdir -p "$SHIM"
    printf '#!/bin/sh\nexit 0\n' >"$SHIM/verible-verilog-format"
    chmod +x "$SHIM/verible-verilog-format"
    export PATH="$SHIM:$PATH"
fi

generate() {
    # $1 = revision, $2 = side name (design1 or design2)
    local rev=$1 side=$2
    local tree=$WORK/py2hwsw_$side
    local gen=$WORK/gen_$side
    local build=$gen/build
    if [ ! -d "$tree" ]; then
        git -C "$REPO" worktree add --detach "$tree" "$rev" >/dev/null
    fi
    # py2hwsw also looks up cores under the current directory, so setup runs
    # from a directory that contains only this side's build output, never the
    # other side's worktree.
    rm -rf "$gen"
    mkdir -p "$gen"
    (cd "$gen" && "$PYTHON" "$tree/py2hwsw/scripts/py2hwsw.py" "$CORE" setup \
        --build_dir "$build" --no_verilog_lint >"$WORK/setup_$side.log" 2>&1)
    # iob_bsp.vh is a board header normally generated by the parent SoC.
    # The library registers include it but use none of its macros, so an
    # empty file is added, identically on both sides.
    if [ ! -f "$build/hardware/src/iob_bsp.vh" ]; then
        echo "// empty board header (normally generated by the parent SoC)" \
            >"$build/hardware/src/iob_bsp.vh"
    fi
    ls "$build"/hardware/src/*.v >/dev/null
}

echo "== $CORE: $SHORT^ (design 1) vs $SHORT (design 2)"
git -C "$REPO" log -1 --format='   %h %ad %s' --date=short "$COMMIT"

generate "$COMMIT^" design1
generate "$COMMIT" design2

SRC1=$WORK/gen_design1/build/hardware/src
SRC2=$WORK/gen_design2/build/hardware/src

# Guard: if both generated trees are identical, the comparison is trivial.
if diff -rq "$SRC1" "$SRC2" >/dev/null; then
    echo "   error: the generated sources of both sides are identical;"
    echo "   $SHORT does not change $CORE, or generation picked the wrong tree."
    exit 65
fi
echo "   generated sources differ in: $(diff -rq "$SRC1" "$SRC2" | sed -E 's|.*/([^/ ]+) and .*|\1|' | sort -u | tr '\n' ' ')"

set +e
"$KEPLER_FORMAL" -sv -v sec \
    --sec-engine "$ENGINE" --sec-encoding binary -k "$MAX_K" \
    --sec-reset-cycles "$RESET_CYCLES" --sec-reset-port "$RESET_PORT" \
    --sv_design1_top "$CORE" --sv_design2_top "$CORE" \
    --design1 "$SRC1"/*.v \
    --design2 "$SRC2"/*.v \
    >"$WORK/kepler-formal.log" 2>&1
STATUS=$?
set -e

grep -E "SEC checked-output coverage|SEC proved|No difference|inconclusive|did not produce|Observed output mismatches|design0=.*design1=" \
    "$WORK/kepler-formal.log" | sed 's/^\[[^]]*\] \[[^]]*\] \[[^]]*\] \[[^]]*\] /   /' | head -12
case $STATUS in
    0) echo "   verdict: proved (exit 0)" ;;
    1) echo "   verdict: partially proved (exit 1)" ;;
    2) echo "   verdict: inconclusive (exit 2)" ;;
    3) echo "   verdict: counterexample (exit 3)" ;;
    *) echo "   verdict: error (exit $STATUS), see $WORK/kepler-formal.log" ;;
esac
echo "   full log: ${WORK#$REPO/}/kepler-formal.log"
exit $STATUS
